  const trimKey = value => value.replace(/\s+/g,' ').trim();

  const textNodes = [];
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = node.parentElement;
      if (!parent || ['SCRIPT','STYLE','NOSCRIPT'].includes(parent.tagName) || parent.closest('.lang-switch')) return NodeFilter.FILTER_REJECT;
      return trimKey(node.nodeValue || '') ? NodeFilter.FILTER_ACCEPT : NodeFilter.FILTER_REJECT;
    }
  });
  while (walker.nextNode()) {
    const node = walker.currentNode;
    textNodes.push({node, original:node.nodeValue});
  }

  const attrNodes = [...document.querySelectorAll('[aria-label]')].map(el => ({
    el,
    original: el.getAttribute('aria-label')
  }));

  const translateText = (original, lang) => {
    if (lang !== 'ru') return original;
    const key = trimKey(original);
    const translated = RU[key];
    if (!translated) return original;
    const lead = original.match(/^\s*/)?.[0] || '';
    const tail = original.match(/\s*$/)?.[0] || '';
    return lead + translated + tail;
  };

  const pageFile = location.pathname.split('/').pop() || 'index.html';
  const caseName = document.querySelector('.case-title')?.textContent?.trim();
  const getSeo = (lang) => {
    if (caseName) {
      return lang === 'ru'
        ? [`${caseName} — кейс TEKEA Design Studio`, `${caseName} — кейс TEKEA Design Studio. Полная презентация проекта и визуальной системы.`]
        : [`${caseName} — TEKEA Design Studio`, `${caseName} case study by TEKEA Design Studio — project presentation and visual system.`];
    }
    return SEO[pageFile]?.[lang];
  };

  const apply = lang => {
    const safe = lang === 'ru' ? 'ru' : 'en';
    document.documentElement.lang = safe;
    document.documentElement.dataset.language = safe;

    textNodes.forEach(({node,original}) => {
      node.nodeValue = translateText(original, safe);
    });

    // Critical branded lines use explicit translations as a final source of truth.
    // This avoids partial/stale rendering on mobile Safari when inline text is split
    // across nested span/em elements.
    document.querySelectorAll('[data-i18n-en][data-i18n-ru]').forEach(el => {
      el.textContent = safe === 'ru' ? el.dataset.i18nRu : el.dataset.i18nEn;
    });

    attrNodes.forEach(({el,original}) => {
      el.setAttribute('aria-label', safe === 'ru' ? (ARIA_RU[original] || original) : original);
    });

    document.querySelectorAll('.lang-switch button').forEach(btn => {
      const active = btn.dataset.lang === safe;
      btn.classList.toggle('is-active', active);
      btn.setAttribute('aria-pressed', String(active));
    });

    const seo = getSeo(safe);
    if (seo) {
      document.title = seo[0];
      const desc = document.querySelector('meta[name="description"]');
      if (desc) desc.content = seo[1];
      const ogTitle = document.querySelector('meta[property="og:title"]');
      const ogDesc = document.querySelector('meta[property="og:description"]');
      if (ogTitle) ogTitle.content = seo[0];
      if (ogDesc) ogDesc.content = seo[1];
    }

    localStorage.setItem('tekea-language', safe);
    window.dispatchEvent(new CustomEvent('tekea:languagechange', {detail:{lang:safe}}));
  };

  document.querySelectorAll('.lang-switch button').forEach(btn =>
    btn.addEventListener('click', () => apply(btn.dataset.lang))
  );

  const initial = localStorage.getItem('tekea-language') ||
    (navigator.language?.toLowerCase().startsWith('ru') ? 'ru' : 'en');
  apply(initial);
